-- V005 - Perfis de acesso do painel web (RF01).
-- Cada perfil diz quais áreas do painel o usuário enxerga: Análises (pública), Coleta e Sistema.
-- Os 3 perfis padrão (ADMINISTRADOR, PESQUISADOR, VISUALIZADOR) são fixos; o administrador
-- pode criar perfis novos e editar as áreas deles.
-- O enum usuario.perfil continua valendo para o tipo de credencial (código no app x e-mail/senha na web).
SET search_path = oto, public;

CREATE TABLE perfil_acesso (
    id              smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            varchar(60) NOT NULL CHECK (btrim(nome) <> ''),
    padrao          boolean     NOT NULL DEFAULT false,
    acesso_analises boolean     NOT NULL DEFAULT true,
    acesso_coleta   boolean     NOT NULL DEFAULT false,
    acesso_sistema  boolean     NOT NULL DEFAULT false,
    criado_em       timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_perfil_acesso_nome ON perfil_acesso (upper(nome));

INSERT INTO perfil_acesso (id, nome, padrao, acesso_analises, acesso_coleta, acesso_sistema) VALUES
    (1, 'ADMINISTRADOR', true, true,  true,  true),
    (2, 'PESQUISADOR',   true, false, false, false),
    (3, 'VISUALIZADOR',  true, true,  false, false);
SELECT setval(pg_get_serial_sequence('oto.perfil_acesso', 'id'), 100);  -- perfis criados pelo admin começam em 101

-- Perfis padrão são imutáveis (nem renomear, nem mudar áreas, nem apagar).
CREATE FUNCTION fn_perfil_padrao_imutavel() RETURNS trigger
LANGUAGE plpgsql SET search_path = oto, pg_catalog AS $$
BEGIN
    IF OLD.padrao THEN
        RAISE EXCEPTION 'perfil padrão % não pode ser alterado', OLD.nome;
    END IF;
    IF TG_OP = 'UPDATE' AND NEW.padrao THEN
        RAISE EXCEPTION 'não é possível transformar um perfil em padrão';
    END IF;
    RETURN COALESCE(NEW, OLD);
END $$;
CREATE TRIGGER trg_perfil_padrao_imutavel BEFORE UPDATE OR DELETE ON perfil_acesso
    FOR EACH ROW EXECUTE FUNCTION fn_perfil_padrao_imutavel();

CREATE TRIGGER trg_auditoria AFTER INSERT OR UPDATE OR DELETE ON perfil_acesso
    FOR EACH ROW EXECUTE FUNCTION fn_auditar();

-- Vínculo usuário -> perfil de acesso. Quem não informa recebe o perfil de mesmo nome do enum,
-- assim os seeds e o bootstrap antigos continuam funcionando.
ALTER TABLE usuario ADD COLUMN perfil_acesso_id smallint REFERENCES perfil_acesso(id);
UPDATE usuario u SET perfil_acesso_id = p.id FROM perfil_acesso p WHERE p.nome = u.perfil::text;

CREATE FUNCTION fn_usuario_perfil_padrao() RETURNS trigger
LANGUAGE plpgsql SET search_path = oto, pg_catalog AS $$
BEGIN
    IF NEW.perfil_acesso_id IS NULL THEN
        SELECT id INTO NEW.perfil_acesso_id FROM perfil_acesso WHERE padrao AND nome = NEW.perfil::text;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_usuario_perfil_padrao BEFORE INSERT OR UPDATE ON usuario
    FOR EACH ROW EXECUTE FUNCTION fn_usuario_perfil_padrao();

ALTER TABLE usuario ALTER COLUMN perfil_acesso_id SET NOT NULL;
CREATE INDEX ix_usuario_perfil_acesso ON usuario (perfil_acesso_id);

-- Permissões: só o painel web gerencia perfis; BI apenas lê; o app não vê.
GRANT SELECT, INSERT, UPDATE ON perfil_acesso TO oto_web;
GRANT SELECT ON perfil_acesso TO oto_readonly;
GRANT SELECT (perfil_acesso_id) ON usuario TO oto_readonly;
